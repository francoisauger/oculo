#!/usr/bin/env python3
"""Oculo (0.11.0, M10): turns the outline icons of settings-redesign.html (ICON) into Android vector drawables in
common/src/main/res/drawable/ (circles and rounded rectangles become paths). Run from the repo root."""
import re
s = open('docs/mockups/settings/settings-redesign.html').read()
a = s.index('const ICON = {'); b = s.index('};', a)
icons = dict(re.findall(r"(\w+):'([^']*)'", s[a:b]))

def f(x):
    return ('%.3f' % float(x)).rstrip('0').rstrip('.')

def to_paths(svg):
    out = []
    for tag, attrs in re.findall(r'<(\w+)([^>]*)/>', svg):
        a = dict(re.findall(r'(\w+)="([^"]*)"', attrs))
        if tag == 'path':
            out.append(a['d'])
        elif tag == 'circle':
            cx, cy, r = float(a['cx']), float(a['cy']), float(a['r'])
            out.append('M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0' % (f(cx - r), f(cy), f(r), f(r), f(2 * r), f(r), f(r), f(-2 * r)))
        elif tag == 'rect':
            x, y, w, h = float(a['x']), float(a['y']), float(a['width']), float(a['height'])
            rx = min(float(a.get('rx', 0)), w / 2, h / 2)
            out.append('M%s,%s h%s a%s,%s 0 0,1 %s,%s v%s a%s,%s 0 0,1 %s,%s h%s a%s,%s 0 0,1 %s,%s v%s a%s,%s 0 0,1 %s,%s z' % (
                f(x + rx), f(y), f(w - 2 * rx), f(rx), f(rx), f(rx), f(rx), f(h - 2 * rx), f(rx), f(rx), f(-rx), f(rx),
                f(-(w - 2 * rx)), f(rx), f(rx), f(-rx), f(-rx), f(-(h - 2 * rx)), f(rx), f(rx), f(rx), f(-rx)))
    return out

names = {'play': 'oculo_settings_ic_play', 'subs': 'oculo_settings_ic_subs', 'home': 'oculo_settings_ic_home',
         'acct': 'oculo_settings_ic_account', 'shield': 'oculo_settings_ic_shield', 'remote': 'oculo_settings_ic_remote',
         'info': 'oculo_settings_ic_info', 'tune': 'oculo_settings_ic_tune', 'gear': 'oculo_ic_settings',
         'chev': 'oculo_settings_ic_chevron', 'hist': 'oculo_settings_ic_recent'}
for k, n in names.items():
    xml = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Oculo (0.11.0, design.md M10): outline icon « %s » of docs/mockups/settings/settings-redesign.html,' % k,
           '     24dp grid, 2dp rounded stroke (generated by gen_icons.py). Tinted by the view that shows it. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="24dp"', '    android:height="24dp"', '    android:viewportWidth="24"', '    android:viewportHeight="24">']
    for p in to_paths(icons[k]):
        xml += ['    <path', '        android:pathData="%s"' % p, '        android:fillColor="#00000000"',
                '        android:strokeColor="#FFFFFFFF"', '        android:strokeWidth="2"',
                '        android:strokeLineCap="round"', '        android:strokeLineJoin="round" />']
    xml.append('</vector>')
    open('common/src/main/res/drawable/%s.xml' % n, 'w').write('\n'.join(xml) + '\n')
print('ok')
